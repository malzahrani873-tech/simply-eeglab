% Copied from lessons/en/06-03-erplab-amplitude-latency.md. The lesson is the reference.
% Channel index of the LRP difference wave
chan = find(strcmp({ALLERP(1).chanlocs.labels}, 'C3/C4'));
nSets = numel(ALLERP);

% 1) Mean amplitude, 150-400 ms, both bins
[ALLERP, meanAmp] = pop_geterpvalues(ALLERP, [150 400], [1 2], chan, ...
    'Erpsets', 1:nSets, 'Measure', 'meanbl', 'Baseline', 'pre', ...
    'Binlabel', 'on', 'Filename', 'mean_amp_150_400.txt');
meanAmp = squeeze(meanAmp);   % bins x ERPsets
fprintf('Mean amplitude: compatible %.2f uV, incompatible %.2f uV\n', ...
    mean(meanAmp(1, :)), mean(meanAmp(2, :)));

% 2) Negative local peak, 150-400 ms, compatible bin
[ALLERP, peakAmp] = pop_geterpvalues(ALLERP, [150 400], 1, chan, ...
    'Erpsets', 1:nSets, 'Measure', 'peakampbl', 'Peakpolarity', 'negative', ...
    'Neighborhood', 3, 'Peakreplace', 'absolute', 'Baseline', 'pre');
fprintf('Peak amplitude, compatible: %.2f uV\n', mean(peakAmp(:)));

% 3) Negative peak latency, 100-700 ms, both bins
[ALLERP, peakLat] = pop_geterpvalues(ALLERP, [100 700], [1 2], chan, ...
    'Erpsets', 1:nSets, 'Measure', 'peaklatbl', 'Peakpolarity', 'negative', ...
    'Neighborhood', 3, 'Peakreplace', 'absolute', 'Baseline', 'pre');
peakLat = squeeze(peakLat);
fprintf('Peak latency: compatible %.0f ms, incompatible %.0f ms\n', ...
    mean(peakLat(1, :)), mean(peakLat(2, :)));

% 4) The bias of peak measures: measure a window with no signal
[ALLERP, blMean] = pop_geterpvalues(ALLERP, [-100 0], 1, chan, ...
    'Erpsets', 1:nSets, 'Measure', 'meanbl', 'Baseline', 'pre');
[ALLERP, blPeak] = pop_geterpvalues(ALLERP, [-100 0], 1, chan, ...
    'Erpsets', 1:nSets, 'Measure', 'peakampbl', 'Peakpolarity', 'negative', ...
    'Neighborhood', 3, 'Peakreplace', 'absolute', 'Baseline', 'pre');
fprintf('Before the stimulus: mean %.2f uV, negative peak %.2f uV\n', ...
    mean(blMean(:)), mean(blPeak(:)));
