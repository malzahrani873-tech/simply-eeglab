function items = sea_data(cfg)
% SEA_DATA  Every data file the lessons and figure scripts need, where it goes and how to get it.
%   items(k).name     short name shown in messages
%   items(k).check    file that must exist after download (a pattern with ** is allowed)
%   items(k).lessons  lessons that need it (verify_batch checks only the items of the lessons it runs)
%   items(k).get      'url' (direct download), 'osf' (ERP CORE on OSF, found by name) or 'manual'
%   items(k).how      URL list, OSF search, or the instruction printed when it is missing
% Used by sea_download.m (evening before the run day) and by verify_batch (before the first lesson).

ds18 = 'https://s3.amazonaws.com/openneuro.org/ds002718/';
ds80 = 'https://s3.amazonaws.com/openneuro.org/ds002680/';
d4 = {'dataset_description.json', 'README', 'task-FaceRecognition_events.json', ...
    'sub-002/eeg/sub-002_task-FaceRecognition_eeg.set', 'sub-002/eeg/sub-002_task-FaceRecognition_eeg.json', ...
    'sub-002/eeg/sub-002_task-FaceRecognition_channels.tsv', 'sub-002/eeg/sub-002_task-FaceRecognition_electrodes.tsv', ...
    'sub-002/eeg/sub-002_task-FaceRecognition_events.tsv'};
d6 = {'dataset_description.json', 'README', 'participants.tsv', 'participants.json'};
parts = {'eeg.set', 'eeg.json', 'channels.tsv', 'electrodes.tsv', 'coordsystem.json', 'events.tsv', 'events.json'};
for s = {'sub-002', 'sub-005'}
    for p = parts
        d6{end + 1} = sprintf('%s/ses-01/eeg/%s_ses-01_task-gonogo_run-1_%s', s{1}, s{1}, p{1}); %#ok<AGROW>
    end
end

items = struct('name', {}, 'check', {}, 'lessons', {}, 'get', {}, 'how', {}, 'dest', {});
items(end + 1) = item('D2 EEGMMIDB S001R03.edf', cfg.d2, ...
    {'import-raw', 'alleeg-datasets', 'channel-locations', 'events'}, 'url', ...
    {'https://physionet.org/files/eegmmidb/1.0.0/S001/S001R03.edf'}, cfg.d2);
items(end + 1) = item('D4 ds002718 sub-002', fullfile(cfg.course_dir, 'ds002718', 'sub-002', 'eeg', 'sub-002_task-FaceRecognition_eeg.set'), ...
    {'bids-openneuro'}, 'url', strcat(ds18, d4), fullfile(cfg.course_dir, 'ds002718', d4));
items(end + 1) = item('D6 ds002680 subset (sub-002, sub-005)', fullfile(cfg.course_dir, 'ds002680', 'sub-005', 'ses-01', 'eeg', 'sub-005_ses-01_task-gonogo_run-1_eeg.set'), ...
    {'study-from-bids'}, 'url', strcat(ds80, d6), fullfile(cfg.course_dir, 'ds002680', d6));
items(end + 1) = item('D6 ready STUDY animal_study.zip', fullfile(cfg.course_dir, 'animal_study.zip'), ...
    {'study-concepts', 'create-study', 'study-precompute', 'study-design', 'study-plot-channels', ...
    'study-statistics', 'study-export-results', 'ic-clustering', 'limo'}, 'url', ...
    {'https://sccn.ucsd.edu/eeglab/download/animal_study.zip'}, fullfile(cfg.course_dir, 'animal_study.zip'));
items(end + 1) = item('ERP CORE N170, participant 2 (intermediate files)', ...
    fullfile(cfg.datadir, 'ERP_CORE', 'N170', '2', '2_N170_shifted_ds_reref_ucbip_hpfilt_ica_corr_cbip.set'), ...
    {'mvpa'}, 'osf', {'N170', '^2_N170_shifted_ds_reref_ucbip_hpfilt_ica_corr_cbip\.(set|fdt)$', 1}, ...
    fullfile(cfg.datadir, 'ERP_CORE', 'N170'));
items(end + 1) = item('ERP CORE N400, raw files of 10 participants', ...
    fullfile(cfg.datadir, 'ERP_CORE', 'N400', '**', '*_N400.set'), ...
    {'bad-channels'}, 'osf', {'N400', '^\d+_N400\.(set|fdt)$', 10}, fullfile(cfg.datadir, 'ERP_CORE', 'N400'));
items(end + 1) = item('Luck (2022) chapter 10 ERPsets', ...
    fullfile(cfg.course_dir, 'Chapter_10', 'Data', 'ERPsets_CI_Diff', '*.erp'), ...
    {'erplab-amplitude-latency', 'data-quality-sme'}, 'manual', ...
    sprintf(['Download chapter 10 of "Applied Event-Related Potential Data Analysis" (DOI 10.18115/D50056) ' ...
    'and unzip the whole Chapter_10 folder into %s'], cfg.course_dir), cfg.course_dir);
end

function s = item(name, check, lessons, get, how, dest)
s = struct('name', name, 'check', check, 'lessons', {lessons}, 'get', get, 'how', {how}, 'dest', {dest});
end
